#!/usr/bin/env bash
# Everything a Mac needs to post scheduled tasks unattended (no sudo):
#   1. com.nexus.agent          the relay + scheduler        (scripts/install_daemon.sh)
#   2. com.nexus.chrome<PORT>   the posting Chrome with --remote-debugging-port, at login,
#                               only if nothing is listening on that port yet (never kills one)
#   3. com.nexus.caffeinate     `caffeinate -s -i` (no system/idle sleep while on AC power)
#
#   ./scripts/install_autostart_mac.sh            install + load all three
#   ./scripts/install_autostart_mac.sh --no-load  write files only
#   SKIP_RELAY=1 / SKIP_CHROME=1 / SKIP_AWAKE=1   leave one out
# Chrome settings (defaults = the thoshotech posting profile):
#   NEXUS_CHROME_PORT=9233  NEXUS_CHROME_USER_DATA=$HOME/NexusProfiles/chrome-thoshotech
#   NEXUS_CHROME_PROFILE="Profile 21"
# Remove: ./scripts/uninstall_daemon.sh --all
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
[ "$(uname)" = "Darwin" ] || { echo "macOS only" >&2; exit 1; }
LOAD=1; [ "${1:-}" = "--no-load" ] && LOAD=0
UID_N="$(id -u)"
LA="$HOME/Library/LaunchAgents"
SUPPORT="$HOME/Library/Application Support/Nexus"
LOGDIR="$HOME/Library/Logs/Nexus"
mkdir -p "$LA" "$SUPPORT" "$LOGDIR"
xml() { printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'; }
q() { printf '%q' "$1"; }
load() {   # label plist
    [ "$LOAD" = 1 ] || return 0
    launchctl bootout "gui/$UID_N/$1" 2>/dev/null || true
    launchctl bootstrap "gui/$UID_N" "$2"
    launchctl enable "gui/$UID_N/$1"
    echo "→ loaded $1"
}
write_plist() {  # path content
    printf '%s\n' "$2" > "$1.tmp"; plutil -lint "$1.tmp" >/dev/null; mv "$1.tmp" "$1"; echo "→ wrote $1"
}

if [ "${SKIP_RELAY:-0}" != 1 ]; then
    if [ "$LOAD" = 1 ]; then "$ROOT/scripts/install_daemon.sh"; else "$ROOT/scripts/install_daemon.sh" --no-load; fi
fi

if [ "${SKIP_CHROME:-0}" != 1 ]; then
    PORT="${NEXUS_CHROME_PORT:-9233}"
    UDD="${NEXUS_CHROME_USER_DATA:-$HOME/NexusProfiles/chrome-thoshotech}"
    PROF="${NEXUS_CHROME_PROFILE:-Profile 21}"
    CHROME="${NEXUS_CHROME_BIN:-/Applications/Google Chrome.app/Contents/MacOS/Google Chrome}"
    LBL="com.nexus.chrome$PORT"
    L="$SUPPORT/$LBL-launch.sh"
    cat > "$L" <<LS
#!/bin/bash
# Generated by install_autostart_mac.sh. Starts the posting Chrome unless port $PORT is already served.
LOG=$(q "$LOGDIR/$LBL.log")
if /usr/bin/curl -fsS -m 3 http://127.0.0.1:$PORT/json/version >/dev/null 2>&1; then
    echo "\$(date '+%F %T') port $PORT already has a browser; nothing to do" >> "\$LOG"; exit 0
fi
if /bin/ps -axo command= | /usr/bin/grep -F -- "--remote-debugging-port=$PORT" | /usr/bin/grep -vq grep; then
    echo "\$(date '+%F %T') a Chrome with --remote-debugging-port=$PORT is starting; leaving it" >> "\$LOG"; exit 0
fi
echo "\$(date '+%F %T') launching Chrome on $PORT" >> "\$LOG"
exec $(q "$CHROME") --remote-debugging-port=$PORT --user-data-dir=$(q "$UDD") --profile-directory=$(q "$PROF") --no-first-run --no-default-browser-check about:blank
LS
    chmod 755 "$L"; bash -n "$L"
    write_plist "$LA/$LBL.plist" "<?xml version=\"1.0\" encoding=\"UTF-8\"?>
<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">
<plist version=\"1.0\"><dict>
    <key>Label</key><string>$LBL</string>
    <key>ProgramArguments</key><array><string>/bin/bash</string><string>$(xml "$L")</string></array>
    <key>RunAtLoad</key><true/>
    <key>KeepAlive</key><false/>
    <key>ProcessType</key><string>Interactive</string>
    <key>LimitLoadToSessionType</key><string>Aqua</string>
    <key>StandardOutPath</key><string>$(xml "$LOGDIR/$LBL.out.log")</string>
    <key>StandardErrorPath</key><string>$(xml "$LOGDIR/$LBL.err.log")</string>
</dict></plist>"
    load "$LBL" "$LA/$LBL.plist"
fi

if [ "${SKIP_AWAKE:-0}" != 1 ]; then
    LBL="com.nexus.caffeinate"
    write_plist "$LA/$LBL.plist" "<?xml version=\"1.0\" encoding=\"UTF-8\"?>
<!DOCTYPE plist PUBLIC \"-//Apple//DTD PLIST 1.0//EN\" \"http://www.apple.com/DTDs/PropertyList-1.0.dtd\">
<plist version=\"1.0\"><dict>
    <key>Label</key><string>$LBL</string>
    <key>ProgramArguments</key><array><string>/usr/bin/caffeinate</string><string>-s</string><string>-i</string></array>
    <key>RunAtLoad</key><true/>
    <key>KeepAlive</key><true/>
    <key>ThrottleInterval</key><integer>30</integer>
</dict></plist>"
    load "$LBL" "$LA/$LBL.plist"
fi
echo "Done. Status: launchctl print gui/$UID_N/com.nexus.agent | head; curl -s http://127.0.0.1:8712/scheduler"
