#!/usr/bin/env bash
# Install the Nexus relay as a macOS LaunchAgent (starts at login, restarted if it dies).
#   ./scripts/install_daemon.sh             write the launcher + plist and load it
#   ./scripts/install_daemon.sh --no-load   only write them
#   ./scripts/install_daemon.sh --print     print the plist and exit
# Extras (separate LaunchAgents, see docs/tutorials/AUTOSTART.md):
#   ./scripts/install_autostart_mac.sh      relay + posting Chrome (CDP port) + keep-awake
#
# External drive (e.g. /Volumes/SANSSD): launchd starts agents before USB/Thunderbolt
# volumes are mounted, and a plist cannot point at a program on a missing volume. So the
# plist runs the venv's real python (internal disk) with a small launcher
# (~/Library/Application Support/Nexus/<label>-launch.py) that waits for the folder,
# then execs the venv python (same pid: the relay IS the launchd job → KeepAlive works).
# Note: the Antigravity brain discovers the running Antigravity app at request time,
# so the app must be open (and signed in) for Antigravity answers; the relay itself
# starts fine without it and other brains keep working.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LABEL="${NEXUS_DAEMON_LABEL:-com.nexus.agent}"   # use a different label to run two Nexus folders side by side
PLIST="$HOME/Library/LaunchAgents/$LABEL.plist"
PY="$ROOT/.venv/bin/python"
SUPPORT="$HOME/Library/Application Support/Nexus"
LAUNCHER="$SUPPORT/$LABEL-launch.py"
LOGDIR="$HOME/Library/Logs/Nexus"                 # internal disk: usable even while the volume is missing
WAIT_S="${NEXUS_VOLUME_WAIT_S:-600}"
[ "$(uname)" = "Darwin" ] || { echo "macOS only" >&2; exit 1; }
[ -x "$PY" ] || { echo "missing $PY — run ./start.sh once first" >&2; exit 1; }
mkdir -p "$ROOT/logs" "$HOME/Library/LaunchAgents" "$SUPPORT" "$LOGDIR"
xml() { printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'; }
q() { printf '%q' "$1"; }
# The launchd job's program is what macOS privacy (TCC) checks for the external drive, so
# it is the venv's REAL python binary (internal disk) running a stdlib-only launcher —
# not /bin/bash (granting a shell access to the drive would cover every script).
REALPY="$("$PY" -c 'import os, sys; print(os.path.realpath(sys.executable))')"
PORT="$(cd "$ROOT" && "$PY" -c 'import sys; sys.path.insert(0, "agent"); import client_config; print(client_config.relay_port())' 2>/dev/null || echo 8712)"
render_launcher() {
cat <<LS
# Generated by $ROOT/scripts/install_daemon.sh — re-run it to update. stdlib only.
import os, sys, time
ROOT = $(printf '%s' "$ROOT" | "$PY" -c 'import json,sys; print(json.dumps(sys.stdin.read()))')
LOG = $(printf '%s' "$LOGDIR/$LABEL.launcher.log" | "$PY" -c 'import json,sys; print(json.dumps(sys.stdin.read()))')
WAIT_S = $WAIT_S
PORT = $PORT
def log(msg):
    with open(LOG, "a") as f:
        f.write(time.strftime("%Y-%m-%d %H:%M:%S ") + msg + "\n")
relay, py = os.path.join(ROOT, "agent", "nexus_relay.py"), os.path.join(ROOT, ".venv", "bin", "python")
waited = 0
while not os.path.isdir(os.path.join(ROOT, "agent")):
    if waited == 0:
        log("waiting for " + ROOT + " (volume not mounted yet?)")
    if waited >= WAIT_S:
        log(ROOT + " still missing after %ss; launchd will retry" % WAIT_S)
        sys.exit(75)
    time.sleep(5)
    waited += 5
try:
    os.chdir(ROOT)
    with open(relay, "rb") as f:
        f.read(1)
except OSError as e:
    log("cannot read %s: %s. macOS privacy is blocking background access to the drive: give Full Disk Access "
        "to %s (System Settings > Privacy & Security > Full Disk Access), then: launchctl kickstart -k gui/%d/$LABEL"
        % (relay, e, os.path.realpath(sys.executable), os.getuid()))
    time.sleep(60)          # KeepAlive retries; do not spin
    sys.exit(78)
# Never run two relays: if one is already serving the port (e.g. started by hand),
# wait for it to stop, then take over (no downtime, no "address in use" restart loop).
import socket
def busy():
    try:
        socket.create_connection(("127.0.0.1", PORT), timeout=2).close()
        return True
    except OSError:
        return False
if busy():
    log("another relay is serving :%d; waiting for it to stop before taking over" % PORT)
    while busy():
        time.sleep(15)
os.makedirs(os.path.join(ROOT, "logs"), exist_ok=True)
out = os.open(os.path.join(ROOT, "logs", "daemon.out.log"), os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o644)
err = os.open(os.path.join(ROOT, "logs", "daemon.err.log"), os.O_WRONLY | os.O_CREAT | os.O_APPEND, 0o644)
os.dup2(out, 1)
os.dup2(err, 2)
log("starting relay (pid %d)" % os.getpid())
os.execv(py, [py, "agent/nexus_relay.py"])      # same pid: the relay IS the launchd job (KeepAlive)
LS
}
render() {
cat <<PL
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key><string>$LABEL</string>
    <key>ProgramArguments</key>
    <array>
        <string>$(xml "$REALPY")</string>
        <string>$(xml "$LAUNCHER")</string>
    </array>
    <!-- relay: $(xml "$ROOT/agent/nexus_relay.py") (python: $(xml "$PY")) -->
    <key>WorkingDirectory</key><string>$(xml "$HOME")</string>
    <key>EnvironmentVariables</key>
    <dict>
        <key>PATH</key><string>/usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin:/usr/sbin:/sbin</string>
        <key>PYTHONUNBUFFERED</key><string>1</string>
    </dict>
    <key>RunAtLoad</key><true/>
    <key>KeepAlive</key><true/>
    <key>ThrottleInterval</key><integer>10</integer>
    <key>ProcessType</key><string>Interactive</string>
    <key>StandardOutPath</key><string>$(xml "$LOGDIR/$LABEL.out.log")</string>
    <key>StandardErrorPath</key><string>$(xml "$LOGDIR/$LABEL.err.log")</string>
</dict>
</plist>
PL
}
case "${1:-}" in
    --print) render; exit 0 ;;
esac
# Never silently take over a LaunchAgent that runs ANOTHER Nexus folder.
if [ -f "$PLIST" ] && ! grep -qF "$(xml "$ROOT/agent/nexus_relay.py")" "$PLIST" && [ "${FORCE:-0}" != "1" ]; then
    echo "$PLIST already runs a different Nexus folder:" >&2
    grep -o '[^ ]*nexus_relay.py' "$PLIST" >&2 || true
    echo "Use NEXUS_DAEMON_LABEL=com.nexus.agent.<name> for a second copy, or FORCE=1 to replace it." >&2
    exit 1
fi
if [ -f "$PLIST" ]; then cp -p "$PLIST" "$PLIST.bak-$(date +%Y%m%d-%H%M%S)"; fi
render_launcher > "$LAUNCHER.tmp" && "$REALPY" -m py_compile "$LAUNCHER.tmp" && mv "$LAUNCHER.tmp" "$LAUNCHER"
rm -f "$SUPPORT/$LABEL-launch.sh"
render > "$PLIST.tmp"
plutil -lint "$PLIST.tmp" >/dev/null
mv "$PLIST.tmp" "$PLIST"
echo "→ wrote $PLIST"
echo "→ wrote $LAUNCHER (waits up to ${WAIT_S}s for $ROOT)"
echo "  launchd program (grant it Full Disk Access if the drive is blocked): $REALPY"
if [ "${1:-}" = "--no-load" ]; then exit 0; fi
launchctl bootout "gui/$(id -u)/$LABEL" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST"
launchctl enable "gui/$(id -u)/$LABEL"
echo "→ loaded $LABEL (logs: $ROOT/logs/daemon.*.log, launcher: $LOGDIR/)"
echo "  check: curl -s http://127.0.0.1:$PORT/health"
